-- Reversible integration checks. All fixture rows and storage metadata roll back.
BEGIN;
DO $$
DECLARE lid uuid:=gen_random_uuid(); aid uuid; hid uuid; mid uuid; rev int; artifacts jsonb; denied boolean;
BEGIN
 SELECT id INTO aid FROM auth.users WHERE email='admin@portal.invalid';
 SELECT id INTO hid FROM auth.users WHERE email='zain@portal.invalid';
 SELECT id INTO mid FROM auth.users WHERE email='marketing@portal.invalid';
 IF aid IS NULL OR hid IS NULL OR mid IS NULL THEN RAISE EXCEPTION 'Required account missing'; END IF;
 INSERT INTO public.listings(id,listing_date,listing_month,listing_year,advisor,property_name,location,listing_type,property_type,price,photos,documents)
 VALUES(lid,current_date,extract(month from current_date),extract(year from current_date),'TRANSACTION QA','TRANSACTION QA','QA','Rent','Studio',1,'[{},{},{},{}]','[]');
 IF (SELECT stage FROM public.listing_progress WHERE id=lid)<>'pending' THEN RAISE EXCEPTION 'Submission projection failed'; END IF;
 PERFORM set_config('request.jwt.claim.sub',hid::text,true);
 PERFORM public.review_listing(lid,'verified');
 IF (SELECT stage FROM public.listing_progress WHERE id=lid)<>'approved' THEN RAISE EXCEPTION 'Listing approval projection failed'; END IF;
 denied:=false;BEGIN PERFORM public.advance_design(lid,'start',0); EXCEPTION WHEN OTHERS THEN denied:=true;END;
 IF NOT denied THEN RAISE EXCEPTION 'Head can mutate design';END IF;
 PERFORM set_config('request.jwt.claim.sub',mid::text,true);
 denied:=false;BEGIN PERFORM public.advance_design(lid,'start',0); EXCEPTION WHEN OTHERS THEN denied:=true;END;
 IF NOT denied THEN RAISE EXCEPTION 'Marketing can start design';END IF;
 PERFORM set_config('request.jwt.claim.sub',aid::text,true);
 PERFORM public.advance_design(lid,'start',0);
 denied:=false;BEGIN PERFORM public.advance_design(lid,'complete',NULL); EXCEPTION WHEN OTHERS THEN denied:=true;END;
 IF NOT denied THEN RAISE EXCEPTION 'Null revision accepted';END IF;
 denied:=false;BEGIN PERFORM public.advance_design(lid,'complete',1,'[]'); EXCEPTION WHEN OTHERS THEN denied:=true;END;
 IF NOT denied THEN RAISE EXCEPTION 'Missing artwork accepted';END IF;
 INSERT INTO storage.objects(bucket_id,name,metadata) VALUES('design-files',lid::text||'/feed.png','{"mimetype":"image/png"}'),('design-files',lid::text||'/story.png','{"mimetype":"image/png"}');
 artifacts:=jsonb_build_array(jsonb_build_object('kind','feed','path',lid::text||'/feed.png','name','feed.png','type','image/png'),jsonb_build_object('kind','story','path',lid::text||'/story.png','name','story.png','type','image/png'));
 denied:=false;BEGIN PERFORM public.advance_design(lid,'complete',0,artifacts); EXCEPTION WHEN OTHERS THEN denied:=true;END;
 IF NOT denied THEN RAISE EXCEPTION 'Stale revision accepted';END IF;
 denied:=false;BEGIN PERFORM public.advance_design(lid,'complete',1,jsonb_set(artifacts,'{1,path}',to_jsonb(lid::text||'/feed.png'))); EXCEPTION WHEN OTHERS THEN denied:=true;END;
 IF NOT denied THEN RAISE EXCEPTION 'Duplicate artwork accepted';END IF;
 PERFORM public.advance_design(lid,'complete',1,artifacts);
 IF (SELECT stage FROM public.listing_progress WHERE id=lid)<>'design_completed' THEN RAISE EXCEPTION 'Completion projection failed';END IF;
 PERFORM public.advance_design(lid,'submit_review',2);
 PERFORM set_config('request.jwt.claim.sub',mid::text,true);
 denied:=false;BEGIN PERFORM public.advance_design(lid,'approve',3, '[]',NULL); EXCEPTION WHEN OTHERS THEN denied:=true;END;
 IF NOT denied THEN RAISE EXCEPTION 'Approver not required';END IF;
 denied:=false;BEGIN PERFORM public.advance_design(lid,'request_changes',3,'[]','Dalal — Marketing Head',''); EXCEPTION WHEN OTHERS THEN denied:=true;END;
 IF NOT denied THEN RAISE EXCEPTION 'Change reason not required';END IF;
 PERFORM public.advance_design(lid,'request_changes',3,'[]','Dalal — Marketing Head','Please revise');
 IF NOT EXISTS(SELECT 1 FROM public.design_events WHERE listing_id=lid AND actor=mid AND approver='Dalal — Marketing Head' AND comment='Please revise') THEN RAISE EXCEPTION 'Audit actor or approver missing';END IF;
 PERFORM set_config('request.jwt.claim.sub',aid::text,true);
 PERFORM public.advance_design(lid,'start',4);
 PERFORM public.advance_design(lid,'complete',5,artifacts);
 PERFORM public.advance_design(lid,'revise',6);
 PERFORM public.advance_design(lid,'complete',7,artifacts);
 PERFORM public.advance_design(lid,'submit_review',8);
 PERFORM set_config('request.jwt.claim.sub',mid::text,true);
 PERFORM public.advance_design(lid,'approve',9,'[]','Shahad — Coordinator','Approved');
 IF NOT EXISTS(SELECT 1 FROM public.listing_progress WHERE id=lid AND stage='design_approved' AND approver='Shahad — Coordinator' AND approved_at IS NOT NULL) THEN RAISE EXCEPTION 'Final approval projection failed';END IF;
 denied:=false;BEGIN PERFORM public.advance_design(lid,'approve',9,'[]','Shahad — Coordinator'); EXCEPTION WHEN OTHERS THEN denied:=true;END;
 IF NOT denied THEN RAISE EXCEPTION 'Repeat approval accepted';END IF;
 IF has_function_privilege('anon','public.advance_design(uuid,text,integer,jsonb,text,text)','EXECUTE') THEN RAISE EXCEPTION 'Anonymous design action permitted';END IF;
 IF has_table_privilege('anon','public.design_workflows','SELECT') THEN RAISE EXCEPTION 'Private workflow exposed';END IF;
 IF NOT has_table_privilege('anon','public.listing_progress','SELECT') THEN RAISE EXCEPTION 'Public dashboard not accessible';END IF;
END $$;
ROLLBACK;
SELECT 'PASS: lifecycle, permissions, both artwork files, revisions, approver, comments, audit and public progress; fixtures rolled back' AS result;
